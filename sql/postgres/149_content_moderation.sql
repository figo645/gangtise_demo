CREATE TABLE IF NOT EXISTS content_moderation_keywords (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    keyword VARCHAR(120) NOT NULL UNIQUE,
    category VARCHAR(80) NOT NULL DEFAULT '金融合规',
    risk_level VARCHAR(20) NOT NULL DEFAULT 'medium' CHECK (risk_level IN ('low', 'medium', 'high')),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    description VARCHAR(500) NOT NULL DEFAULT '',
    created_by VARCHAR(120) NOT NULL DEFAULT '',
    updated_by VARCHAR(120) NOT NULL DEFAULT '',
    created_at VARCHAR(40) NOT NULL DEFAULT CURRENT_TIMESTAMP::text,
    updated_at VARCHAR(40) NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE TABLE IF NOT EXISTS content_moderation_audits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_slug VARCHAR(80) NOT NULL DEFAULT '',
    source_type VARCHAR(40) NOT NULL,
    entity_id VARCHAR(180) NOT NULL DEFAULT '',
    actor_user_id VARCHAR(120) NOT NULL DEFAULT '',
    actor_name VARCHAR(120) NOT NULL DEFAULT '',
    result VARCHAR(20) NOT NULL CHECK (result IN ('clear', 'alert')),
    risk_level VARCHAR(20) NOT NULL DEFAULT 'none',
    matched_keywords_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    content_sha256 VARCHAR(64) NOT NULL,
    created_at VARCHAR(40) NOT NULL DEFAULT CURRENT_TIMESTAMP::text
);

CREATE INDEX IF NOT EXISTS idx_content_moderation_audits_created_at
    ON content_moderation_audits (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_content_moderation_audits_scope
    ON content_moderation_audits (tenant_slug, source_type, result, id DESC);

